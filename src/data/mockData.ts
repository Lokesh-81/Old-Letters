// Reliable template resolver with aliases for legacy IDs
export function getTemplate(id?: string, fallback?: LetterTemplate): LetterTemplate {
  if (fallback) return fallback;
  if (!id) return TEMPLATES[0];
  const normalized = id.toLowerCase().trim();
  const directMatch = TEMPLATES.find((t) => t.id === normalized);
  if (directMatch) return directMatch;

  // Legacy & convenient alias mapping
  if (normalized === 'midnight' || normalized === 'midnight-correspondence' || normalized === 'midnight-archive') {
    return TEMPLATES.find((t) => t.id === 'midnight-archive') || TEMPLATES[1];
  }
  if (normalized === 'vellum' || normalized === 'wax-vellum' || normalized === 'antique-vellum') {
    return TEMPLATES.find((t) => t.id === 'antique-vellum') || TEMPLATES[2];
  }
  if (
    normalized === 'burgundy' ||
    normalized === 'blush' ||
    normalized === 'blush-pressed-rose'
  ) {
    return TEMPLATES.find((t) => t.id === 'blush-pressed-rose') || TEMPLATES[3];
  }
  if (normalized === 'love' || normalized === 'love-letter') {
    return TEMPLATES.find((t) => t.id === 'love-letter') || TEMPLATES[4];
  }
  if (normalized === 'typewritten' || normalized === 'typewriter') {
    return TEMPLATES.find((t) => t.id === 'typewriter') || TEMPLATES[5];
  }
  if (normalized === 'diary' || normalized === 'personal-diary') {
    return TEMPLATES.find((t) => t.id === 'personal-diary') || TEMPLATES[6];
  }
  if (normalized === 'postcard' || normalized === 'vintage-postcard') {
    return TEMPLATES.find((t) => t.id === 'vintage-postcard') || TEMPLATES[7];
  }
  if (normalized === 'photo' || normalized === 'archival-photo') {
    return TEMPLATES.find((t) => t.id === 'archival-photo') || TEMPLATES[8];
  }
  if (normalized === 'botanical' || normalized === 'botanical-archive') {
    return TEMPLATES.find((t) => t.id === 'botanical-archive') || TEMPLATES[9];
  }
  if (normalized === 'capsule' || normalized === 'time-capsule') {
    return TEMPLATES.find((t) => t.id === 'time-capsule') || TEMPLATES[10];
  }
  if (normalized === 'flowers' || normalized === 'pressed-flowers') {
    return TEMPLATES.find((t) => t.id === 'pressed-flowers') || TEMPLATES[11];
  }
  if (normalized === 'secret' || normalized === 'secret-letter') {
    return TEMPLATES.find((t) => t.id === 'secret-letter') || TEMPLATES[12];
  }
  if (normalized === 'future' || normalized === 'future-letter') {
    return TEMPLATES.find((t) => t.id === 'future-letter') || TEMPLATES[13];
  }

  return TEMPLATES[0];
}

